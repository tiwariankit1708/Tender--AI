"""Pydantic schemas for Agent D (Auditor) — Day 10.

Kept completely independent from evaluation schemas so audit
records can be versioned, stored, and queried separately.
"""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field

from app.schemas.evaluation import (
    EvaluationDecision,
    EvaluationResult,
    EvidenceChunk,
)


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class AuditVerdict(str, Enum):
    """High-level conclusion reached by Agent D."""

    CONFIRMED = "CONFIRMED"
    FLAGGED = "FLAGGED"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"


class AuditIssueType(str, Enum):
    """Specific category of discrepancy detected by the auditor."""

    NONE = "NONE"
    UNSUPPORTED_ASSERTION = "UNSUPPORTED_ASSERTION"
    CONTRADICTION = "CONTRADICTION"
    MISSING_EVIDENCE = "MISSING_EVIDENCE"
    HALLUCINATED_QUOTE = "HALLUCINATED_QUOTE"
    NUMERICAL_MISMATCH = "NUMERICAL_MISMATCH"
    AMBIGUOUS_EVIDENCE = "AMBIGUOUS_EVIDENCE"


# ---------------------------------------------------------------------------
# Core audit record
# ---------------------------------------------------------------------------

class AuditRecord(BaseModel):
    """Single audit finding generated by Agent D for one criterion."""

    audit_id: str = Field(
        description="Unique identifier, e.g. AUD-C001-A3F2B1.",
    )
    criterion_id: str
    requirement: str

    # What Agent C said
    agent_c_decision: EvaluationDecision

    # What Agent D concluded
    auditor_verdict: AuditVerdict
    recommended_decision: EvaluationDecision
    confidence_score: float = Field(
        ge=0.0,
        le=1.0,
        description="Auditor confidence in the recommended decision.",
    )
    issue_type: AuditIssueType = AuditIssueType.NONE
    auditor_reasoning: str = Field(
        description="Detailed critique and justification.",
    )
    quotes_verified: bool = Field(
        default=True,
        description="True if all cited quotes exist verbatim in the raw chunks.",
    )
    requires_human_intervention: bool = False
    timestamp: str = ""


# ---------------------------------------------------------------------------
# Request / response payloads
# ---------------------------------------------------------------------------

class AuditSingleRequest(BaseModel):
    """Audit a single evaluation result from Agent C."""

    evaluation: EvaluationResult
    raw_evidence: Optional[list[EvidenceChunk]] = None


class BatchAuditRequest(BaseModel):
    """Audit every evaluation for a bidder in one call."""

    bidder_document_id: str
    evaluations: list[EvaluationResult]


class BatchAuditResult(BaseModel):
    """Aggregated audit summary for a bidder."""

    bidder_document_id: str
    total_audited: int
    confirmed_count: int
    flagged_count: int
    human_review_count: int
    audit_records: list[AuditRecord]
